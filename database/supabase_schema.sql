-- Enable UUID extension if needed
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- -----------------------------------------------------------------------------
-- 01. TABLE: contact_messages
-- Stores visitor inquiries submitted via the portfolio contact form.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.contact_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT NOT NULL,
    subject TEXT DEFAULT '',
    message TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- -----------------------------------------------------------------------------
-- 02. TABLE: meeting_bookings
-- Stores visitor appointment requests for Google Meet sessions.
-- Supports preferred_date, preferred_time, status, meeting_link, and notes.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.meeting_bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT NOT NULL,
    purpose TEXT NOT NULL,
    preferred_date DATE NOT NULL,
    preferred_time TEXT NOT NULL,
    status TEXT DEFAULT 'Pending' NOT NULL,
    meeting_link TEXT DEFAULT '',
    notes TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- -----------------------------------------------------------------------------
-- 03. TABLE: projects
-- Dynamic showcase of authentic AI & software systems engineered by Sahil.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT NOT NULL,
    technologies TEXT NOT NULL,
    github_url TEXT DEFAULT '',
    live_demo_url TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- -----------------------------------------------------------------------------
-- 04. TABLE: education
-- Formal undergraduate degrees and specialized higher education programs.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.education (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution TEXT NOT NULL,
    degree TEXT NOT NULL,
    field TEXT NOT NULL,
    location TEXT NOT NULL,
    start_date TEXT NOT NULL,
    end_date TEXT NOT NULL,
    status TEXT NOT NULL,
    logo_url TEXT DEFAULT ''
);

-- -----------------------------------------------------------------------------
-- 05. TABLE: experience
-- Professional venture leadership, company track record, and operational scope.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.experience (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name TEXT NOT NULL,
    role TEXT NOT NULL,
    duration TEXT NOT NULL,
    description TEXT NOT NULL,
    powered_by TEXT DEFAULT ''
);

-- -----------------------------------------------------------------------------
-- 06. TABLE: skills
-- Grouped technical capabilities across programming, web, AI, and business.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_name TEXT NOT NULL,
    category TEXT NOT NULL
);

-- -----------------------------------------------------------------------------
-- INDEXES (Optimized Query Performance)
-- -----------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_contact_messages_email ON public.contact_messages(email);
CREATE INDEX IF NOT EXISTS idx_contact_messages_created ON public.contact_messages(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_meeting_bookings_email_date ON public.meeting_bookings(email, preferred_date);
CREATE INDEX IF NOT EXISTS idx_meeting_bookings_created ON public.meeting_bookings(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_projects_created ON public.projects(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_skills_category ON public.skills(category);

